// Writes src/providers/price-list.gen.ts: the rows of LiteLLM's price map the ADK prices from,
// trimmed to the providers it prices and their cost fields, one model a line. The ADK ships this snapshot
// and prices from it with no network request; run this before a release so its prices are current.
//
//   node scripts/update-prices.mjs                 fetch LiteLLM's main branch
//   node scripts/update-prices.mjs <file-or-url>   read a saved copy instead

import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'
const TARGET = new URL('../src/providers/price-list.gen.ts', import.meta.url)

/** The registry providers `providers/pricing.ts` looks models up under. */
const PROVIDERS = new Set([
  'openai',
  'gemini',
  'vertex_ai',
  'vertex_ai-language-models',
  'vertex_ai-anthropic_models',
  'anthropic',
  'voyage',
])

/**
 * Whether a row keeps `field`: its provider and every numeric cost or multiplier, so a rate
 * `providers/pricing.ts` starts reading is already in the snapshot.
 */
function kept(field, value) {
  return (
    field === 'litellm_provider' || (typeof value === 'number' && /_cost|_multiplier/.test(field))
  )
}

async function read(source) {
  if (!/^https?:/.test(source)) return JSON.parse(readFileSync(source, 'utf8'))
  const response = await fetch(source, { signal: AbortSignal.timeout(30_000) })
  if (!response.ok) throw new Error(`${source} answered ${response.status}`)
  return response.json()
}

const source = process.argv[2] ?? SOURCE
const registry = await read(source)
const rows = Object.entries(registry)
  .filter(([, entry]) => PROVIDERS.has(entry?.litellm_provider))
  .map(([model, entry]) => [
    model,
    Object.fromEntries(Object.entries(entry).filter(([field, value]) => kept(field, value))),
  ])
  .filter(([, entry]) => Object.keys(entry).length > 1)
  .toSorted(([a], [b]) => a.localeCompare(b))

if (rows.length === 0) throw new Error(`${source} has no rows for ${[...PROVIDERS].join(', ')}`)

const asOf = new Date().toISOString().slice(0, 10)
const lines = rows.map(([model, entry]) => `  ${JSON.stringify(model)}: ${JSON.stringify(entry)},`)
writeFileSync(
  TARGET,
  [
    `// GENERATED by packages/agents/adk/scripts/update-prices.mjs from LiteLLM's price map on ${asOf}.`,
    '// Do not edit: run `pnpm --filter @animahealth/adk run prices` and commit the result.',
    '',
    '/** LiteLLM price-map rows for the providers the ADK prices, keyed by model. */',
    'export const PRICE_LIST: Record<string, Record<string, number | string>> = {',
    ...lines,
    '}',
    '',
  ].join('\n'),
)
console.log(`Wrote ${rows.length} models to ${TARGET.pathname}`)
