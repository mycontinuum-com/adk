/**
 * Postbuild script: replace dist/cli/index.js (CJS) with a thin wrapper that does
 * `import('./index.mjs')` at runtime.
 *
 * Ink >= 5 is ESM-only (yoga-layout uses top-level await). CJS consumers cannot `require('ink')`.
 * This wrapper keeps: - `require('@animahealth/adk/cli')` - the internal
 * `require('./cli/index.js')` emitted by the main CJS bundle working by dynamically importing the
 * ESM implementation.
 */

'use strict'

const fs = require('fs')
const path = require('path')

const target = path.join(__dirname, '..', 'dist', 'cli', 'index.js')

const wrapper = `/**
 * AUTO-GENERATED by scripts/postbuild-cli-cjs-wrapper.cjs
 *
 * CJS wrapper — bridges into the ESM CLI implementation via dynamic import().
 * Ink >= 5 is ESM-only so CJS cannot require('ink') directly.
 */
'use strict';

function isPromiseLike(v) {
  return !!v && (typeof v === 'object' || typeof v === 'function') && typeof v.then === 'function';
}

exports.cli = function cli(runnable, inputOrConfig) {
  var resolve;
  var reject;
  var resultPromise = new Promise(function (res, rej) {
    resolve = res;
    reject = rej;
  });

  var handle = {
    runner: undefined,
    session: undefined,
    runnable: runnable,
    then: function (onfulfilled, onrejected) {
      return resultPromise.then(onfulfilled, onrejected);
    },
  };

  (async function () {
    try {
      var mod = await import('./index.mjs');
      if (!mod || typeof mod.cli !== 'function') {
        throw new Error('Failed to load ESM CLI implementation (missing export "cli")');
      }

      var implHandle =
        inputOrConfig === undefined ? mod.cli(runnable) : mod.cli(runnable, inputOrConfig);

      if (implHandle && typeof implHandle === 'object') {
        handle.runner = implHandle.runner;
        handle.session = implHandle.session;
        handle.runnable = implHandle.runnable || runnable;
      }

      if (!isPromiseLike(implHandle)) {
        resolve(implHandle);
        return;
      }

      implHandle.then(resolve, reject);
    } catch (err) {
      reject(err);
    }
  })();

  return handle;
};
`

fs.writeFileSync(target, wrapper, 'utf8')
console.log('[postbuild] Wrote CJS→ESM CLI wrapper:', target)
